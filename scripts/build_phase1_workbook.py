def put_row(ws, r, label, values=None, formula=None, fmt=KFMT, font=None, derived=False, n=NM, ytd_col=YTD_COL):
    lab = ws.cell(row=r, column=1, value=label + (" (derived)" if derived else ""))
    if font:
        lab.font = font
    if derived:
        lab.font = F_FLAG
    for i in range(n):
        col = 2 + i
        if values is not None:
            c = ws.cell(row=r, column=col, value=values[i])
        else:
            c = ws.cell(row=r, column=col, value=formula(get_column_letter(col)))
        c.number_format = fmt
        c.border = BOX
    last = get_column_letter(1 + n)
    y = ws.cell(row=r, column=ytd_col, value=f"=SUM(B{r}:{last}{r})")
    y.number_format = fmt
    y.border = BOX
    y.fill = FILL_TOT
    return r + 1


