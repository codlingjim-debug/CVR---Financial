def header(ws, row, cols, labels):
    for c, label in zip(cols, labels):
        cell = ws.cell(row=row, column=c, value=label)
        cell.font = F_H
        cell.fill = FILL_H
        cell.alignment = Alignment(horizontal="center", wrap_text=True)
        cell.border = BOX


def title(ws, text, sub=None):
    ws["A1"] = text
